import { describe, expect, it } from 'vitest'
import { josa } from '../../src/logic/josa'

describe('josa', () => {
  it.each([
    ['빅데이터관리', '과/와', '빅데이터관리와'],
    ['머신러닝', '과/와', '머신러닝과'],
    ['빅데이터분석', '을/를', '빅데이터분석을'],
    ['빅데이터초급', '은/는', '빅데이터초급은'],
    ['빅데이터고급', '이/가', '빅데이터고급이'],
    ['빅데이터마이닝', '으로/로', '빅데이터마이닝으로'],
    ['데이터 설계자', '으로/로', '데이터 설계자로'],
    ['Q8', '으로/로', 'Q8로'],
    ['교통빅데이터', '이/가', '교통빅데이터가'],
    ['빅데이터개론Ⅰ', '은/는', '빅데이터개론Ⅰ은'],
    ['회귀분석Ⅰ', '을/를', '회귀분석Ⅰ을'],
    ['Q5', '으로/로', 'Q5로'],  ] as const)('%s + %s → %s', (w, p, out) => {
    expect(josa(w, p)).toBe(out)
  })
})
